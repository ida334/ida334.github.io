// Writes assets/img/terrazzo.svg: a seamless 240px tile of terrazzo chips in the site's palette.
// Usage: node tools/make-terrazzo.mjs
import { writeFileSync } from 'node:fs';

const SIZE = 240;
const colors = ['#18222a', '#557189', '#2c7a69', '#f5f7f6', '#2466a8', '#9aa6ad'];
let seed = 11;
const rnd = () => (seed = (seed * 9301 + 49297) % 233280) / 233280;

function chip(cx, cy) {
  const r = 2 + rnd() * 5;
  const sides = 4 + Math.floor(rnd() * 3);
  const start = rnd() * Math.PI;
  const pts = [];
  for (let i = 0; i < sides; i++) {
    const a = start + (i / sides) * Math.PI * 2;
    const k = r * (0.6 + rnd() * 0.6);
    pts.push(`${(cx + Math.cos(a) * k).toFixed(1)},${(cy + Math.sin(a) * k).toFixed(1)}`);
  }
  return pts.join(' ');
}

const shapes = [];
for (let i = 0; i < 90; i++) {
  const x = rnd() * SIZE;
  const y = rnd() * SIZE;
  const fill = colors[Math.floor(rnd() * colors.length)];
  const opacity = (0.35 + rnd() * 0.45).toFixed(2);
  // draw edge chips on the opposite side too, so the tile repeats without seams
  for (const [dx, dy] of [[0, 0], [SIZE, 0], [-SIZE, 0], [0, SIZE], [0, -SIZE]]) {
    const cx = x + dx, cy = y + dy;
    if (cx < -10 || cx > SIZE + 10 || cy < -10 || cy > SIZE + 10) continue;
    shapes.push(`<polygon points="${chip(cx, cy)}" fill="${fill}" fill-opacity="${opacity}"/>`);
  }
}

const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${SIZE}" height="${SIZE}" viewBox="0 0 ${SIZE} ${SIZE}">
<!-- Terrazzo tile for the ground floor. Generated by tools/make-terrazzo.mjs; no external source. -->
<rect width="${SIZE}" height="${SIZE}" fill="#d8dcd9"/>
${shapes.join('\n')}
</svg>
`;
writeFileSync('assets/img/terrazzo.svg', svg);
console.log('wrote assets/img/terrazzo.svg with', shapes.length, 'chips');
